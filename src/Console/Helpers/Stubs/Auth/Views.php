    <div class="col-md-6 bg-light p-3">
        <h3 class="text-center">Register Here!</h3>
        <hr>
        <form class="form" action="" method="post" enctype="multipart/form-data">
            <?= csrf() ?>
            <?= errorBag(\$this->displayErrors) ?>
            <?= text("User name", 'username', \$this->user->username, ['class' => 'form-control input-sm'], ['class' => 'form-group mb-3']) ?>
            
            <!-- Primary profile details -->
            <?= \$this->component('edit_profile_details') ?>
            
            <?= fileSelector("Upload Profile Image (Optional)", 'profileImage', ['class' => 'form-control', 'accept' => 'image/png image/jpeg image/png'], ['class' => 'form-group mb-3']) ?>
            
            <?= \$this->component('password_complexity_requirements', true); ?>

            <?= password("Password", 'password', \$this->user->password, ['class' => 'form-control input-sm'], ['class' => 'form-group mb-3']) ?>
            <?= confirm("Confirm Password", \$this->user->confirm, ['class' => 'form-control input-sm'], ['class' => 'form-group mb-3']) ?>
            <?= submitBlock('Register', ['class' => 'btn btn-large btn-primary'], ['class' => 'text-end'])  ?>
        </form>
    </div>
</div>

<!-- Wait until content is loaded before we initialize script -->
<?= initTinyMCE('description') ?>

<?php \$this->end(); ?>
PHP;
    }

    /**
     * Generates the React.js version of the password reset view.
     *
     * @return string The view's contents.
     */
    public static function makeResetPasswordJS(): string {
        return <<<'JSX'
import React from "react";
import {PasswordComplexityRequirements} from '@chappy/components/PasswordComplexityRequirements';
import { documentTitle } from "@chappy/utils";

import { CSRFInput, Password, Confirm } from "@chappy/components/Forms";
import { DisplayErrors as Errors } from "@chappy/components/Forms";
import { SubmitTag as Submit } from "@chappy/utils";

/**
 * Render component for password reset view.
 * 
 * @property {object} user The user whose password to be reset.
 * @property {array} errors The errors generated by the users model.
 * @param {InputProps} param0 
 * @returns {JSX.Element} Component for password reset view.
 */
function ResetPassword({ user, errors }) {
    documentTitle("Reset Password");
    return (
        <div className="row align-items-center justify-content-center">
            <div className="col-md-6 bg-light p-3">
                <h3 className="text-center">Reset Password</h3>
                <PasswordComplexityRequirements />
                <form className="form" action="" method="post">
                    <CSRFInput />
                    <Errors errors={errors} />
                    <Password 
                        label="Password"
                        name="password"
                        value={user.password}
                        inputAttrs={{className: "form-control input-sm"}}
                        divAttrs={{className: "form-group mb-3"}}
                    />
                    <Confirm 
                        label="Confirm Password"
                        name="confirm"
                        value={user.confirm}
                        inputAttrs={{className: "form-control input-sm"}}
                        divAttrs={{className: "form-group mb-3"}}
                    />
                    <Submit label="Set Password" inputAttrs={{className: "btn btn-primary"}} />
                </form>
            </div>
        </div>
    );
}        
export default ResetPassword;
JSX;
    }

