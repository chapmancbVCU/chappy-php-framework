<?php
declare(strict_types=1);
namespace Console\Helpers\Stubs\Auth;

/**
 * Contains stubs for auth views.
 */
class Views {
    /**
     * The React.js version of the login view.
     *
     * @return string The view's contents.
     */
    public static function makeLoginJS(): string {
        return <<<'JSX'
import React from "react";
import {
    CSRFInput,
    DisplayErrors,
    Password,
    RememberMe,
    route,
    SubmitTag,
    Text,
} from '@chappy/utils';

/**
 * @property {object} errors The errors object.
 * @property {object} login The login model object
 * @param {InputProps} param0 
 * @returns {JSX.Element} The contents 
 */
function Login({errors, login, rememberMeChecked}) {
    return(
        <div className="row align-items-center justify-content-center">
            <div className="col-md-6 bg-light p-3">
                <h1 className="text-center">Login</h1>
                <form className="form" action={route('auth.login')} method="post">
                    <CSRFInput />
                    <DisplayErrors errors={errors}/>
                    <Text 
                        label="Username"
                        name="username"
                        value={login.username}
                        inputAttrs={{className: 'form-control'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Password 
                        label="Password"
                        name="password"
                        value={login.password}
                        inputAttrs={{className: 'form-control'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <RememberMe
                        label="Remember Me"
                        checked={rememberMeChecked}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <div className="d-flex justify-content-end">
                        <div className="flex-grow-1 text-body">
                            Don't have an account? <a href={route('auth.register')}>Sign Up</a>
                        </div>
                        <SubmitTag label={"login"} inputAttrs={{className: 'btn btn-primary'}}/>
                    </div>
                </form>
            </div>
        </div>
    )
}

export default Login;
JSX;
    }

    /**
     * PHP version of login view.
     *
     * @return string The view's contents.
     */
    public function makeLoginPHP(): string {
        return <<<PHP
<?php \$this->start('head'); ?>
<?php \$this->end(); ?>

<?php \$this->start('body'); ?>
<div class="row align-items-center justify-content-center">
    <div class="col-md-6 bg-light p-3">
        <h3 class="text-center">Log In</h3>
        <form class="form" action="<?=route('auth.login')?>" method="post">
            <?= csrf() ?>
            <?= errorBag(\$this->displayErrors) ?>
            <?= text('Username', 'username', \$this->login->username, ['class' => 'form-control'], ['class' => 'form-group mb-3']); ?>
            <?= password('Password', 'password', \$this->login->password,['class' => 'form-control'], ['class' => 'form-group mb-3']); ?>
            <?= rememberMe('Remember Me', \$this->login->getRememberMeChecked(), [], ['class' => 'form-group mb-3']); ?>
            <div class="d-flex justify-content-end">
                <div class="flex-grow-1 text-body">Don't have an account? <a href="<?=route('auth.register')?>">Sign Up</a></div>
                <?= submit('Login',['class'=>'btn btn-primary']) ?>
            </div>
        </form>
    </div>
</div>
<?php \$this->end(); ?>
PHP;
    }

    /**
     * Generates the React.js version of the register view.
     *
     * @return string The view's contents.
     */
    public function makeRegisterJS(): string {
        return <<<'JSX'
import React from "react";
import {PasswordComplexityRequirements} from '@chappy/components/PasswordComplexityRequirements';
import { Forms, RichText } from '@chappy/utils';

/**
 * Generates the register view component
 * @property {object} user The users model object.
 * @property {object} errors The errors generated by the users model.
 * @param {InputProps} param0 
 * @returns {JSX.Element} The register view component.
 */
function Register({user, errors}) {
    return (
        <div className="row align-items-center justify-content-center">
            <div className="col-md-6 bg-light p-3">
                <h3 className="text-center">Register Here!</h3>
                <hr />
                <form action="" className="form" method="post" encType="multipart/form-data">
                    <Forms.CSRFInput />
                    <Forms.DisplayErrors errors={errors}/>
                    <Forms.Text 
                        label="User name"
                        name="username"
                        value={user.username}
                        inputAttrs={{className: 'form-control input-sm'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Forms.Text 
                        label="First Name"
                        name="fname"
                        value={user.fname}
                        inputAttrs={{className: 'form-control input-sm'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Forms.Text 
                        label="Last Name"
                        name="lname"
                        value={user.lname}
                        inputAttrs={{className: 'form-control input-sm'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Forms.Email 
                        label="Email"
                        name="email"
                        value={user.email}
                        inputAttrs={{className: 'form-control input-sm', placeholder: 'joe@example.com'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <RichText
                        label="Description"
                        name="description"
                        value={user.description || ""}
                        inputAttrs={{ placeholder: 'Describe yourself here...' }}
                        divAttrs={{ className: 'form-group mb-3' }}
                    />
                    <Forms.FileSelector 
                        label="Upload Profile Image (Optional)"
                        name="profileImage"
                        value=""
                        inputAttrs={{className: 'form-control', accept: 'image/gif image/jpeg image/png'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <PasswordComplexityRequirements />
                    <Forms.Password 
                        label="Password"
                        name="password"
                        value={user.password}
                        inputAttrs={{className: 'form-control input-sm'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Forms.Confirm 
                        label="Confirm Password"
                        name="confirm"
                        value={user.confirm}
                        inputAttrs={{className: 'form-control input-sm'}}
                        divAttrs={{className: 'form-group mb-3'}}
                    />
                    <Forms.SubmitBlock
                        label="Register"
                        inputAttrs={{className: 'btn btn-large btn-primary'}}
                        divAttrs={{className: 'text-end'}}
                    />           
                </form>
            </div>
        </div>
    );
}

export default Register;
JSX;
    }

    /**
     * Generates the PHP version of the register view.
     *
     * @return string The view's contents.
     */
    public static function makeRegisterPHP(): string {
        return <<<PHP
<?php \$this->setSiteTitle("Register Here!"); ?>
